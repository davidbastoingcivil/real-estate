-- Additive GeoAI and location intelligence schema.
-- Does not recreate, rename, or delete the existing public.properties table.
begin;

create schema if not exists extensions;
create extension if not exists postgis with schema extensions;

create table if not exists public.spatial_pois (
  id bigint generated by default as identity primary key,
  external_id text,
  name text not null,
  category text not null check (category in (
    'commerce', 'transport', 'education', 'health', 'recreation',
    'services', 'infrastructure', 'risk', 'competitor'
  )),
  subcategory text not null default '',
  source_name text not null,
  source_url text,
  source_updated_at timestamptz,
  location extensions.geography(Point, 4326) not null,
  attributes jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint spatial_pois_source_external_id_unique unique (source_name, external_id)
);

create table if not exists public.spatial_areas (
  id bigint generated by default as identity primary key,
  external_id text,
  name text not null,
  area_type text not null,
  source_name text not null,
  source_updated_at timestamptz,
  boundary extensions.geometry(MultiPolygon, 4326) not null,
  attributes jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint spatial_areas_source_external_id_unique unique (source_name, external_id)
);

create table if not exists public.properties_geoai_metrics (
  property_id bigint primary key references public.properties(id) on delete cascade,
  accessibility_score numeric(5,2),
  commercial_density_score numeric(5,2),
  infrastructure_growth_score numeric(5,2),
  risk_score numeric(5,2),
  opportunity_score numeric(5,2),
  poi_counts jsonb not null default '{}'::jsonb,
  analysis_radius_m integer not null default 1500,
  confidence text not null default 'no_data'
    check (confidence in ('no_data', 'limited', 'moderate', 'good')),
  model_version text not null default 'heuristic-v1',
  calculated_at timestamptz not null default now()
);

create index if not exists spatial_pois_location_gist_idx
  on public.spatial_pois using gist (location);
create index if not exists spatial_pois_category_idx
  on public.spatial_pois (category, subcategory);
create index if not exists spatial_areas_boundary_gist_idx
  on public.spatial_areas using gist (boundary);
create index if not exists spatial_areas_type_idx
  on public.spatial_areas (area_type);

alter table public.spatial_pois enable row level security;
alter table public.spatial_areas enable row level security;
alter table public.properties_geoai_metrics enable row level security;

revoke all on public.spatial_pois, public.spatial_areas, public.properties_geoai_metrics from anon, authenticated;
grant select on public.properties_geoai_metrics to authenticated;
grant select, insert, update, delete on public.spatial_pois, public.spatial_areas to authenticated;

drop policy if exists "Admins can manage spatial POIs" on public.spatial_pois;
create policy "Admins can manage spatial POIs" on public.spatial_pois
  for all to authenticated
  using (exists (select 1 from public.admin_users where user_id = (select auth.uid())))
  with check (exists (select 1 from public.admin_users where user_id = (select auth.uid())));

drop policy if exists "Admins can manage spatial areas" on public.spatial_areas;
create policy "Admins can manage spatial areas" on public.spatial_areas
  for all to authenticated
  using (exists (select 1 from public.admin_users where user_id = (select auth.uid())))
  with check (exists (select 1 from public.admin_users where user_id = (select auth.uid())));

drop policy if exists "Admins can read GeoAI metrics" on public.properties_geoai_metrics;
create policy "Admins can read GeoAI metrics" on public.properties_geoai_metrics
  for select to authenticated
  using (exists (select 1 from public.admin_users where user_id = (select auth.uid())));

create or replace function public.get_location_intelligence_score(
  lat double precision,
  lng double precision,
  radius_meters integer
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  origin extensions.geography(Point, 4326);
  safe_radius integer := coalesce(radius_meters, 1500);
  counts jsonb;
  total_count integer;
  access_count integer;
  commerce_count integer;
  infrastructure_count integer;
  risk_count integer;
  access_score numeric(5,2);
  commerce_score numeric(5,2);
  infrastructure_score numeric(5,2);
  risk_score numeric(5,2);
  opportunity_score numeric(5,2);
begin
  if lat is null or lng is null or lat < -90 or lat > 90 or lng < -180 or lng > 180
     or (lat = 0 and lng = 0) then
    raise exception 'Coordinates must be valid latitude/longitude.' using errcode = '22023';
  end if;
  if safe_radius < 100 or safe_radius > 50000 then
    raise exception 'radius_meters must be between 100 and 50000.' using errcode = '22023';
  end if;

  origin := extensions.st_setsrid(extensions.st_makepoint(lng, lat), 4326)::extensions.geography;

  select coalesce(jsonb_object_agg(category, poi_count), '{}'::jsonb), coalesce(sum(poi_count), 0)::integer
  into counts, total_count
  from (
    select category, count(*)::integer as poi_count
    from public.spatial_pois
    where extensions.st_dwithin(location, origin, safe_radius)
    group by category
  ) grouped_pois;

  access_count := coalesce((counts->>'transport')::integer, 0)
    + coalesce((counts->>'education')::integer, 0)
    + coalesce((counts->>'health')::integer, 0)
    + coalesce((counts->>'recreation')::integer, 0)
    + coalesce((counts->>'services')::integer, 0);
  commerce_count := coalesce((counts->>'commerce')::integer, 0)
    + coalesce((counts->>'competitor')::integer, 0);
  infrastructure_count := coalesce((counts->>'infrastructure')::integer, 0);
  risk_count := coalesce((counts->>'risk')::integer, 0);

  if total_count > 0 then
    access_score := round(least(access_count / 25.0, 1.0) * 100, 2);
    commerce_score := round(least(commerce_count / 40.0, 1.0) * 100, 2);
    infrastructure_score := round(least(infrastructure_count / 12.0, 1.0) * 100, 2);
    risk_score := round(least(risk_count / 10.0, 1.0) * 100, 2);
    opportunity_score := round(greatest(0, least(100,
      (0.35 * access_score) + (0.30 * commerce_score)
      + (0.25 * infrastructure_score) - (0.10 * risk_score)
    )), 2);
  end if;

  return jsonb_build_object(
    'radius_meters', safe_radius,
    'poi_counts', counts,
    'total_pois', total_count,
    'accessibility_score', access_score,
    'commercial_density_score', commerce_score,
    'infrastructure_growth_score', infrastructure_score,
    'risk_score', risk_score,
    'opportunity_score', opportunity_score,
    'confidence', case when total_count = 0 then 'no_data'
      when total_count < 8 then 'limited' when total_count < 25 then 'moderate' else 'good' end,
    'model_version', 'heuristic-v1',
    'calculated_at', now()
  );
end;
$$;

create or replace function public.get_location_intelligence_heatmap(
  lat double precision,
  lng double precision,
  radius_meters integer,
  cell_size_meters integer default 400
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  origin extensions.geography(Point, 4326);
  safe_radius integer := coalesce(radius_meters, 1500);
  safe_cell integer := coalesce(cell_size_meters, 400);
  lat_step double precision;
  lng_step double precision;
  features jsonb;
begin
  if lat is null or lng is null or lat < -90 or lat > 90 or lng < -180 or lng > 180
     or (lat = 0 and lng = 0) then
    raise exception 'Coordinates must be valid latitude/longitude.' using errcode = '22023';
  end if;
  if safe_radius < 100 or safe_radius > 50000 or safe_cell < 150 or safe_cell > 5000 then
    raise exception 'radius_meters must be 100-50000 and cell_size_meters must be 150-5000.' using errcode = '22023';
  end if;

  origin := extensions.st_setsrid(extensions.st_makepoint(lng, lat), 4326)::extensions.geography;
  lat_step := safe_cell / 111320.0;
  lng_step := safe_cell / (111320.0 * greatest(abs(cos(radians(lat))), 0.05));

  with located_pois as (
    select p.category, p.subcategory,
      extensions.st_y(p.location::extensions.geometry) as poi_lat,
      extensions.st_x(p.location::extensions.geometry) as poi_lng
    from public.spatial_pois p
    where extensions.st_dwithin(p.location, origin, safe_radius)
  ), positioned as (
    select floor((poi_lat - lat) / lat_step)::integer as row_key,
      floor((poi_lng - lng) / lng_step)::integer as column_key,
      category, poi_lat, poi_lng
    from located_pois
  ), cell_stats as (
    select row_key, column_key, count(*)::integer as poi_count,
      avg(poi_lat) as center_lat, avg(poi_lng) as center_lng
    from positioned
    group by row_key, column_key
  ), category_counts as (
    select row_key, column_key, category, count(*)::integer as category_count
    from positioned
    group by row_key, column_key, category
  ), cell_categories as (
    select row_key, column_key, jsonb_object_agg(category, category_count) as categories
    from category_counts
    group by row_key, column_key
  ), cells as (
    select stats.row_key, stats.column_key, stats.poi_count, stats.center_lat, stats.center_lng, categories.categories
    from cell_stats stats
    join cell_categories categories using (row_key, column_key)
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'type', 'Feature',
    'geometry', jsonb_build_object('type', 'Point', 'coordinates', jsonb_build_array(center_lng, center_lat)),
    'properties', jsonb_build_object('poi_count', poi_count, 'categories', categories, 'cell_size_meters', safe_cell)
  )), '[]'::jsonb)
  into features from cells;

  return jsonb_build_object('type', 'FeatureCollection', 'features', features,
    'radius_meters', safe_radius, 'cell_size_meters', safe_cell,
    'method', 'poi_count_aggregated_to_local_approximate_grid');
end;
$$;

create or replace function public.get_property_isochrone_buffer(
  lat double precision,
  lng double precision,
  minutes integer,
  travel_mode text default 'walking'
)
returns jsonb
language plpgsql
stable
security invoker
set search_path = ''
as $$
declare
  origin extensions.geography(Point, 4326);
  speed_meters_per_minute numeric;
  radius_meters integer;
  polygon_json jsonb;
begin
  if lat is null or lng is null or lat < -90 or lat > 90 or lng < -180 or lng > 180
     or (lat = 0 and lng = 0) then
    raise exception 'Coordinates must be valid latitude/longitude.' using errcode = '22023';
  end if;
  if minutes is null or minutes < 1 or minutes > 60 then
    raise exception 'minutes must be between 1 and 60.' using errcode = '22023';
  end if;
  if travel_mode not in ('walking', 'driving') then
    raise exception 'travel_mode must be walking or driving.' using errcode = '22023';
  end if;

  speed_meters_per_minute := case travel_mode when 'walking' then 75 else 500 end;
  radius_meters := round(minutes * speed_meters_per_minute)::integer;
  origin := extensions.st_setsrid(extensions.st_makepoint(lng, lat), 4326)::extensions.geography;
  polygon_json := extensions.st_asgeojson(
    extensions.st_buffer(origin, radius_meters)::extensions.geometry
  )::jsonb;

  return jsonb_build_object(
    'type', 'Feature',
    'geometry', polygon_json,
    'properties', jsonb_build_object(
      'requested_minutes', minutes,
      'travel_mode', travel_mode,
      'estimated_radius_meters', radius_meters,
      'is_approximation', true,
      'method', 'radial_buffer_from_assumed_average_speed',
      'source_note', 'No street-network routing or barriers are included.'
    )
  );
end;
$$;

create or replace function public.refresh_property_geoai_metrics(target_property_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  admin_allowed boolean;
  property_row record;
  score jsonb;
begin
  select exists (select 1 from public.admin_users where user_id = (select auth.uid()))
  into admin_allowed;
  if not admin_allowed then
    raise exception 'Only administrators can refresh property metrics.' using errcode = '42501';
  end if;

  select id, lat, lng into property_row
  from public.properties where id = target_property_id;
  if not found then raise exception 'Property not found.' using errcode = 'P0002'; end if;

  score := public.get_location_intelligence_score(property_row.lat::double precision, property_row.lng::double precision, 1500);
  insert into public.properties_geoai_metrics (
    property_id, accessibility_score, commercial_density_score,
    infrastructure_growth_score, risk_score, opportunity_score,
    poi_counts, analysis_radius_m, confidence, model_version, calculated_at
  ) values (
    target_property_id, (score->>'accessibility_score')::numeric,
    (score->>'commercial_density_score')::numeric,
    (score->>'infrastructure_growth_score')::numeric, (score->>'risk_score')::numeric,
    (score->>'opportunity_score')::numeric, score->'poi_counts', 1500,
    score->>'confidence', score->>'model_version', now()
  ) on conflict (property_id) do update set
    accessibility_score = excluded.accessibility_score,
    commercial_density_score = excluded.commercial_density_score,
    infrastructure_growth_score = excluded.infrastructure_growth_score,
    risk_score = excluded.risk_score,
    opportunity_score = excluded.opportunity_score,
    poi_counts = excluded.poi_counts,
    analysis_radius_m = excluded.analysis_radius_m,
    confidence = excluded.confidence,
    model_version = excluded.model_version,
    calculated_at = excluded.calculated_at;
end;
$$;

create or replace function public.on_property_geoai_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  score jsonb;
begin
  if new.lat is null or new.lng is null or new.lat not between -90 and 90
     or new.lng not between -180 and 180 or (new.lat = 0 and new.lng = 0) then
    delete from public.properties_geoai_metrics where property_id = new.id;
    return new;
  end if;

  score := public.get_location_intelligence_score(new.lat::double precision, new.lng::double precision, 1500);
  insert into public.properties_geoai_metrics (
    property_id, accessibility_score, commercial_density_score,
    infrastructure_growth_score, risk_score, opportunity_score,
    poi_counts, analysis_radius_m, confidence, model_version, calculated_at
  ) values (
    new.id, (score->>'accessibility_score')::numeric,
    (score->>'commercial_density_score')::numeric,
    (score->>'infrastructure_growth_score')::numeric, (score->>'risk_score')::numeric,
    (score->>'opportunity_score')::numeric, score->'poi_counts', 1500,
    score->>'confidence', score->>'model_version', now()
  ) on conflict (property_id) do update set
    accessibility_score = excluded.accessibility_score,
    commercial_density_score = excluded.commercial_density_score,
    infrastructure_growth_score = excluded.infrastructure_growth_score,
    risk_score = excluded.risk_score,
    opportunity_score = excluded.opportunity_score,
    poi_counts = excluded.poi_counts,
    analysis_radius_m = excluded.analysis_radius_m,
    confidence = excluded.confidence,
    model_version = excluded.model_version,
    calculated_at = excluded.calculated_at;
  return new;
end;
$$;

drop trigger if exists properties_geoai_metrics_sync on public.properties;
create trigger properties_geoai_metrics_sync
after insert or update of lat, lng on public.properties
for each row execute function public.on_property_geoai_change();

