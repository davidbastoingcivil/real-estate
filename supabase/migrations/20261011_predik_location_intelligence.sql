revoke all on function public.get_property_isochrone_buffer(double precision, double precision, integer, text) from public;
grant execute on function public.get_property_isochrone_buffer(double precision, double precision, integer, text) to anon, authenticated;
revoke all on function public.refresh_property_geoai_metrics(bigint) from public, anon;
grant execute on function public.refresh_property_geoai_metrics(bigint) to authenticated;
revoke all on function public.on_property_geoai_change() from public, anon, authenticated;

commit;
